#!/usr/bin/env python3
"""Generates firmware art assets.

    python3 tools/gen_art.py

- firmware/main/ui/art/earth_land.cpp: a 256x128 equirectangular land mask
  (1 bit per pixel, 4 KB) rasterized from Natural Earth's 1:110m land
  polygons (public domain, https://www.naturalearthdata.com). A PNG preview
  goes to tools/.art-src/earth_land.png.
- firmware/main/ui/art/sprites.{h,cpp}: every tools/sprites/<name>.txt as an
  LVGL 2-bit indexed image `sprite_<name>`. The text files are pixel art, one
  character per pixel: . transparent, r red, w off-white, g grey, k black.

Pure standard library.
"""
import json
import os
import struct
import urllib.request
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools", ".art-src")
ART = os.path.join(ROOT, "firmware", "main", "ui", "art")
OUT = os.path.join(ART, "earth_land.cpp")
SPRITES = os.path.join(ROOT, "tools", "sprites")
# Index 0 is transparent; the rest match ui/theme.h.
SPRITE_COLORS = {"r": (0xFC, 0x3D, 0x21), "w": (0xF2, 0xF2, 0xF2), "g": (0x80, 0x80, 0x80), "k": (0, 0, 0)}
LAND_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson"
W, H = 256, 128


def load_land():
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "ne_110m_land.geojson")
    if not os.path.exists(path):
        urllib.request.urlretrieve(LAND_URL, path)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    rings = []
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            rings.extend(poly)  # holes too: even-odd fill handles them
    return rings


def rasterize(rings):
    """Even-odd scanline fill at pixel centers."""
    bits = [[0] * W for _ in range(H)]
    edges = []
    for ring in rings:
        for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]):
            edges.append((x0, y0, x1, y1))
    for row in range(H):
        lat = 90.0 - (row + 0.5) * 180.0 / H
        xs = []
        for x0, y0, x1, y1 in edges:
            if (y0 > lat) != (y1 > lat):
                xs.append(x0 + (lat - y0) * (x1 - x0) / (y1 - y0))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            c0 = max(0, int((a + 180.0) * W / 360.0 - 0.5 + 1))
            c1 = min(W - 1, int((b + 180.0) * W / 360.0 - 0.5))
            for col in range(c0, c1 + 1):
                bits[row][col] = 1
    return bits


def write_png(path, bits):
    raw = b"".join(b"\x00" + bytes(255 if v else 0 for v in row) for row in bits)

    def chunk(tag, payload):
        return struct.pack(">I", len(payload)) + tag + payload + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def write_c(path, bits):
    lines = [
        "// Generated by tools/gen_art.py from Natural Earth 1:110m land (public domain).",
        "// 256x128 equirectangular land mask, 1 bit per pixel, MSB first.",
        "// Row 0 is latitude +90, column 0 is longitude -180.",
        '#include "earth.h"',
        "",
        "namespace art {",
        "",
        "const uint8_t EarthLand[EarthLandHeight][EarthLandWidth / 8] = {",
    ]
    for row in bits:
        packed = []
        for i in range(0, W, 8):
            byte = 0
            for b in row[i:i + 8]:
                byte = (byte << 1) | b
            packed.append(f"0x{byte:02X}")
        lines.append("\t{ " + ", ".join(packed) + " },")
    lines += ["};", "", "}  // namespace art", ""]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def load_sprite(path):
    rows = [l.rstrip("\n") for l in open(path, encoding="utf-8") if l.strip() and not l.startswith("#")]
    width = max(map(len, rows))
    return [r.ljust(width, ".") for r in rows]


def sprite_c(name, rows):
    used = sorted({c for r in rows for c in r} - {"."})
    if len(used) > 3:
        raise SystemExit(f"{name}: at most 3 colors besides transparent, got {used}")
    index = {".": 0, **{c: i + 1 for i, c in enumerate(used)}}
    palette = [(0, 0, 0, 0)] + [(*SPRITE_COLORS[c], 0xFF) for c in used]
    palette += [(0, 0, 0, 0)] * (4 - len(palette))
    w, h = len(rows[0]), len(rows)
    stride = (w * 2 + 7) // 8
    data = []
    for r, g, b, a in palette:
        data += [b, g, r, a]  # lv_color32_t is BGRA in memory
    for row in rows:
        packed = [0] * stride
        for x, c in enumerate(row):
            packed[x // 4] |= index[c] << (6 - 2 * (x % 4))
        data += packed
    body = ",\n\t".join(", ".join(f"0x{v:02X}" for v in data[i:i + 16]) for i in range(0, len(data), 16))
    return (
        f"static const uint8_t {name}_data[] = {{\n\t{body}\n}};\n"
        f"const lv_image_dsc_t sprite_{name} = {{\n"
        f"\t.header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I2, .flags = 0, .w = {w}, .h = {h}, .stride = {stride}, .reserved_2 = 0 }},\n"
        f"\t.data_size = sizeof({name}_data),\n\t.data = {name}_data,\n\t.reserved = nullptr,\n\t.reserved_2 = nullptr,\n}};\n"
    )


def write_sprites():
    names = sorted(f[:-4] for f in os.listdir(SPRITES) if f.endswith(".txt"))
    header = ["// Generated by tools/gen_art.py from tools/sprites/*.txt.", "#pragma once", "", "#include <lvgl.h>", ""]
    header += [f"extern const lv_image_dsc_t sprite_{n};" for n in names] + [""]
    source = ["// Generated by tools/gen_art.py from tools/sprites/*.txt.", '#include "sprites.h"', ""]
    for n in names:
        source.append(sprite_c(n, load_sprite(os.path.join(SPRITES, n + ".txt"))))
    with open(os.path.join(ART, "sprites.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(header))
    with open(os.path.join(ART, "sprites.cpp"), "w", encoding="utf-8") as f:
        f.write("\n".join(source))
    print(f"{os.path.join(ART, 'sprites.cpp')} ({', '.join(names)})")


def main():
    write_sprites()
    bits = rasterize(load_land())
    write_c(OUT, bits)
    write_png(os.path.join(CACHE, "earth_land.png"), bits)
    land = sum(map(sum, bits)) / (W * H)
    print(f"{OUT} ({land:.0%} land)")


if __name__ == "__main__":
    main()
